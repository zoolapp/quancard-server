export type Locale = "en" | "zh";

function initialLocale(): Locale {
  try {
    const stored = localStorage.getItem("quancard.locale");
    if (stored === "en" || stored === "zh") return stored;
  } catch {
    /* ignore */
  }
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

/** Exposed for the completeness test only. */
export const MESSAGES = { en, zh };

export const locale = signal<Locale>(initialLocale());

export function setLocale(next: Locale): void {
  locale.value = next;
  document.documentElement.lang = next === "zh" ? "zh-Hans" : "en";
  try {
    localStorage.setItem("quancard.locale", next);
  } catch {
    /* ignore */
  }
}

export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
  const table = locale.value === "zh" ? zh : en;
  let text = table[key] ?? en[key] ?? key;
  for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

/** Translate an open enum value, falling back to the stored value itself. */
export function tEnum(group: string, value: string): string {
  const key = `${group}.${value}` as MessageKey;
  return key in en ? t(key) : value;
}

export function regionName(code: string | null): string {
  if (!code) return "";
  try {
    return new Intl.DisplayNames([locale.value === "zh" ? "zh-Hans" : "en"], { type: "region" }).of(code.toUpperCase()) ?? code;
  } catch {
    return code;
  }
}

export function formatTime(epochSeconds: number | string): string {
  const date = typeof epochSeconds === "number" ? new Date(epochSeconds * 1000) : new Date(epochSeconds);
  return new Intl.DateTimeFormat(locale.value === "zh" ? "zh-Hans" : "en", { dateStyle: "medium", timeStyle: "short" }).format(date);
}

/** Short sync stamp: time only for today, otherwise a short date. */
export function formatShort(epochSeconds: number): string {
  const date = new Date(epochSeconds * 1000);
  const today = new Date().toDateString() === date.toDateString();
  return new Intl.DateTimeFormat(locale.value === "zh" ? "zh-Hans" : "en", today ? { timeStyle: "short" } : { dateStyle: "medium" }).format(date);
}

export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / 1024 / 1024).toFixed(1)} MB`;
}
